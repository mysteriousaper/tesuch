// Generates docs/RULES_MATRIX.md from rules/*.json so the matrix never drifts from the engine.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const rules = readdirSync("rules").filter((f) => f.endsWith(".json")).sort()
  .map((f) => JSON.parse(readFileSync(`rules/${f}`, "utf8")));
const esc = (s) => String(s).replace(/\|/g, "\\|");
const rows = rules.map((r) =>
  `| \`${r.id}\` v${r.version} | ${r.article ? `Art. ${r.article}` : "**missing**"} | ${r.status} | ${r.severity} → ${r.status === "verified" ? r.severity : "advisory"} | ${r.scope} | ${esc(r.title.en)} | ${esc(r.basis)} | ${esc(r.edge_cases.join(" ") || "–")} |`);
const pending = rules.filter((r) => r.status !== "verified");
const md = `# Rules matrix

_Generated by \`pnpm rules:matrix\` from \`rules/*.json\`. Do not edit by hand._

**${rules.length} rules, ${pending.length} awaiting lawyer review.** Unverified rules can never raise red alerts; they show as **advisory** with a disclaimer. Article numbers come only from the brief's law-firm summary and are never invented: where none was given, the field is empty.

| Rule | Article | Status | Severity (declared → shown) | Scope | Checks | Basis | Edge cases |
|---|---|---|---|---|---|---|---|
${rows.join("\n")}

## Not implemented yet (needs data we do not collect)

| Topic | Why not yet |
|---|---|
| Severance pay | Needs salary data; collect only after lawyer confirms the formula. |
| Overtime: max 4 h over 2 days, 180 h/year | Needs timesheets. Candidate for a later timesheet import. |
| Working time: max 12 h/day, 48 h/week | Needs timesheets. |
| Maternity 155/180 days | Depends on medical facts we deliberately do not store. |

## Lawyer checklist

For each rule: confirm the article number and wording on arlis.am, replace \`source_url\` with the exact DocumentView link, confirm or correct the edge cases, then set \`status: "verified"\` and bump \`version\`.
`;
writeFileSync("docs/RULES_MATRIX.md", md);
console.log(`docs/RULES_MATRIX.md: ${rules.length} rules`);
